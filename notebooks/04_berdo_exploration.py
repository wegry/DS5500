"""Only office use vs. mixed use buildings"""

import re

office_df = df[
    df["Largest Property Type"] == "Office"
].copy()

description_col = "All Property Types and GFAs (sq ft)"

# Extract property-type names from descriptions
def extract_property_types(description):
    if pd.isna(description):
        return []

    return [
        name.strip()
        for name in re.findall(
            r"([^,]+?)\s*\([-+]?\d+(?:\.\d+)?\)",
            str(description)
        )
    ]

office_df["Property Types"] = (
    office_df[description_col].apply(extract_property_types)
)

office_df["Office Category"] = office_df["Property Types"].apply(
    lambda types:
        "Office Only" if types == ["Office"]
        else "Mixed Use" if "Office" in types
        else "Unknown"
)

# Compare counts and emissions availability
office_df["GHG Numeric"] = pd.to_numeric(
    office_df["Total GHG Emissions (kgCO2e)"],
    errors="coerce"
)

summary = office_df.groupby("Office Category").agg(
    Buildings=("BERDO ID", "count"),
    With_GHG=("GHG Numeric", "count")
)

summary["GHG_Completeness_%"] = (
    summary["With_GHG"] / summary["Buildings"] * 100
).round(1)

display(summary)

# Check which additional property types are most common
from collections import Counter

other_types = Counter(
    t
    for types in office_df["Property Types"]
    for t in types
    if t != "Office"
)

print("\nMost common secondary property types:")
display(pd.Series(other_types).sort_values(ascending=False).head(15))

